//Ans :
//C++ compiler is a program that converts C++ source code into an executable program that the computer can run, we can use a C++ online compiler  and also C++ offline compiler such as GCC (GNU Compiler Collection), Code::Blocks, Microsoft Visual Studio, Dev-C++, and etc. I personally used C++ online compilers using Programiz because it is more compact for me who likes to use mobile phone for coding. 
//a.How to use offline C++ Compiler :
//1. Install a C++ compiler (such as MinGW or g++, etc).
//2.Write your program and save it as a .cpp file (for example main.cpp).
//3.Open the terminal or command prompt.
//4.Compile with typing the program using : g++ main.cpp -o main
//5.Run the program : ./main, on Windows you could run “main.exe”
//b.How to use online C++ Compiler :
//1.Open an online compiler website (for example Programiz, OnlineGDB, or Replit).
//2.Select C++ as the programming language.
//3.Write or paste your C++ code in the editor.
//4.Click the “Run” or “Execute” button.
//5.The program will compile and the output will appear in the console.    